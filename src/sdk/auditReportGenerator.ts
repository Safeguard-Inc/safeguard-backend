import { createHash } from 'crypto';

export interface AuditReportMetadata {
  reportId: string;
  organizationName: string;
  network: string;
  generatedAt: string;
  periodStart: string;
  periodEnd: string;
  policyContractId: string;
  paymentContractId: string;
}

export interface AuditReportMetrics {
  totalTransactionsEvaluated: number;
  approvedTransactions: number;
  escrowedTransactions: number;
  blockedTransactions: number;
  approvalRatePercent: number;
  sanctionsChecksPerformed: number;
  sanctionsHitsBlocked: number;
  totalVolumeXlm: string;
  activeEscrowsRemaining: number;
}

export interface ComplianceCertificate {
  metadata: AuditReportMetadata;
  metrics: AuditReportMetrics;
  certificateHash: string; // SHA-256 checksum of normalized report data
  status: 'COMPLIANT' | 'FLAGGED' | 'NON_COMPLIANT';
  auditorNotes: string;
}

export class AuditReportGenerator {
  /**
   * Compute deterministic SHA-256 integrity hash for an audit payload.
   */
  public static canonicalStringify(obj: any): string {
    if (obj === null || typeof obj !== 'object') {
      return JSON.stringify(obj);
    }
    if (Array.isArray(obj)) {
      return '[' + obj.map((item) => AuditReportGenerator.canonicalStringify(item)).join(',') + ']';
    }
    const keys = Object.keys(obj).sort();
    const entries = keys.map((k) => JSON.stringify(k) + ':' + AuditReportGenerator.canonicalStringify(obj[k]));
    return '{' + entries.join(',') + '}';
  }

  public static computeCertificateHash(data: { metadata: AuditReportMetadata; metrics: AuditReportMetrics }): string {
    const canonicalString = AuditReportGenerator.canonicalStringify(data);
    return createHash('sha256').update(canonicalString).digest('hex');
  }

  /**
   * Determine compliance rating based on blocked transactions and approval threshold.
   */
  public static evaluateCertificateStatus(metrics: AuditReportMetrics): 'COMPLIANT' | 'FLAGGED' | 'NON_COMPLIANT' {
    if (metrics.approvalRatePercent >= 90 && metrics.sanctionsHitsBlocked === 0) {
      return 'COMPLIANT';
    }
    if (metrics.approvalRatePercent >= 70) {
      return 'FLAGGED';
    }
    return 'NON_COMPLIANT';
  }

  /**
   * Generate a complete verified certificate object.
   */
  public generateCertificate(
    metadata: AuditReportMetadata,
    metrics: AuditReportMetrics,
    auditorNotes: string = 'Automated Safeguard on-chain compliance audit verification certificate.'
  ): ComplianceCertificate {
    const certificateHash = AuditReportGenerator.computeCertificateHash({ metadata, metrics });
    const status = AuditReportGenerator.evaluateCertificateStatus(metrics);

    return {
      metadata,
      metrics,
      certificateHash,
      status,
      auditorNotes,
    };
  }

  /**
   * Format certificate as a Markdown document suitable for regulatory submission or export.
   */
  public formatMarkdownReport(cert: ComplianceCertificate): string {
    const { metadata: m, metrics: met } = cert;
    return `# Stellar On-Chain Compliance Audit Certificate

**Report ID:** \`${m.reportId}\`  
**Organization:** ${m.organizationName}  
**Network:** \`${m.network}\`  
**Audit Period:** ${m.periodStart} to ${m.periodEnd}  
**Generated At:** ${m.generatedAt}  
**Verification SHA-256:** \`${cert.certificateHash}\`  
**Verdict:** **${cert.status}**  

---

## 1. Smart Contract Reference
- **Policy Contract:** \`${m.policyContractId}\`
- **Payment Settlement Contract:** \`${m.paymentContractId}\`

---

## 2. Compliance Verification Summary
| Metric | Value |
| :--- | :--- |
| **Total Evaluations** | ${met.totalTransactionsEvaluated.toLocaleString()} |
| **Approved Transactions** | ${met.approvedTransactions.toLocaleString()} (${met.approvalRatePercent}%) |
| **Escrowed (Milestone/Flagged)** | ${met.escrowedTransactions.toLocaleString()} |
| **Blocked (Denylisted/Sanctioned)** | ${met.blockedTransactions.toLocaleString()} |
| **Sanctions Screenings** | ${met.sanctionsChecksPerformed.toLocaleString()} |
| **Total Evaluated Volume** | ${met.totalVolumeXlm} XLM |
| **Active Unsettled Escrows** | ${met.activeEscrowsRemaining.toLocaleString()} |

---

## 3. Provenance & Integrity Attestation
This certificate was cryptographically generated by the Safeguard Stellar Compliance Engine. The checksum \`${cert.certificateHash.slice(0, 16)}...\` verifies that telemetry records have not been altered or tampered with.

*Auditor Note: ${cert.auditorNotes}*
`;
  }
}
